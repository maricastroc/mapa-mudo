export type Globe = { x: number; y: number; r: number };
export type Projected = { x: number; y: number; depth: number };
export type LonLat = [number, number];

const DEG = Math.PI / 180;

export const VIEW = { lon: -64, lat: 16 };

const FORWARD = [Math.cos(VIEW.lat * DEG) * Math.cos(VIEW.lon * DEG), Math.cos(VIEW.lat * DEG) * Math.sin(VIEW.lon * DEG), Math.sin(VIEW.lat * DEG)];
const EAST = [-Math.sin(VIEW.lon * DEG), Math.cos(VIEW.lon * DEG), 0];
const NORTH = [-Math.sin(VIEW.lat * DEG) * Math.cos(VIEW.lon * DEG), -Math.sin(VIEW.lat * DEG) * Math.sin(VIEW.lon * DEG), Math.cos(VIEW.lat * DEG)];

type Vec = [number, number, number];

function dot(a: number[], b: number[]) {
  return a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
}

function surface(lon: number, lat: number, radius = 1): Vec {
  const c = Math.cos(lat * DEG);
  return [radius * c * Math.cos(lon * DEG), radius * c * Math.sin(lon * DEG), radius * Math.sin(lat * DEG)];
}

function project(globe: Globe, p: Vec): Projected {
  return { x: globe.x + globe.r * dot(p, EAST), y: globe.y - globe.r * dot(p, NORTH), depth: dot(p, FORWARD) };
}

export function lonLat(globe: Globe, lon: number, lat: number, radius = 1) {
  return project(globe, surface(lon, lat, radius));
}

function fixed(v: number) {
  return v.toFixed(1);
}

function onLimb(globe: Globe, p: Projected) {
  const dx = p.x - globe.x;
  const dy = p.y - globe.y;
  const len = Math.hypot(dx, dy) || 1;
  return { x: globe.x + (dx / len) * globe.r, y: globe.y + (dy / len) * globe.r };
}

function densify(ring: LonLat[], step = 2) {
  const out: LonLat[] = [];
  for (let i = 0; i < ring.length; i++) {
    const [a, b] = [ring[i], ring[(i + 1) % ring.length]];
    const n = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / step));
    for (let k = 0; k < n; k++) out.push([a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n]);
  }
  return out;
}

export function landPath(globe: Globe, ring: LonLat[]) {
  const points = densify(ring).map(([lon, lat]) => {
    const p = lonLat(globe, lon, lat);
    return p.depth >= 0 ? p : onLimb(globe, p);
  });
  return points.map((p, i) => `${i ? "L" : "M"}${fixed(p.x)} ${fixed(p.y)}`).join("") + "Z";
}

function visibleRuns(points: Projected[], visible: (p: Projected) => boolean) {
  const parts: string[] = [];
  let open = false;
  for (const p of points) {
    if (visible(p)) {
      parts.push(`${open ? "L" : "M"}${fixed(p.x)} ${fixed(p.y)}`);
      open = true;
    } else open = false;
  }
  return parts.join("");
}

export function parallel(globe: Globe, lat: number) {
  const points = Array.from({ length: 181 }, (_, i) => lonLat(globe, -180 + i * 2, lat));
  return visibleRuns(points, (p) => p.depth >= 0);
}

export function meridian(globe: Globe, lon: number) {
  const points = Array.from({ length: 91 }, (_, i) => lonLat(globe, lon, -90 + i * 2));
  return visibleRuns(points, (p) => p.depth >= 0);
}

